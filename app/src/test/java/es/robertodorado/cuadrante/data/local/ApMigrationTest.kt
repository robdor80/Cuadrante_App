class ApMigrationTest {
    @get:Rule val folder = TemporaryFolder()
    // Literal payload emitted by the 1.0.0 codec, not generated by the new implementation.
    private val payload = "D|old-ap|AP|2026-12-01,2026-12-03\nD|old-permission|PERMISSION|2026-12-07,2027-01-05\nR|old-vacation|VACATION|2026-12-28|2027-01-02"
    private val date = LocalDate.of(2026, 12, 1)
    private val now = Instant.parse("2026-11-05T12:00:00Z")
    private val settingsValue = AppSettings(ShiftPatternType.CUSTOM, listOf(ShiftType.MORNING), date)
    private fun create(id: String = "r", offset: Long = 0) = ApChange.Create(id, listOf(ApSelection("$id-day", date.plusDays(offset), 2026)))
    private class Memory : DataStore<Preferences> {
        val state = MutableStateFlow<Preferences>(emptyPreferences())
        val mutex = Mutex()
        var writes = 0
        override val data: Flow<Preferences> = state
        override suspend fun updateData(transform: suspend (Preferences) -> Preferences): Preferences = mutex.withLock {
            val updated = transform(state.value)
            if (updated != state.value) writes++
            state.value = updated
            updated
        }
    }
    private suspend fun repository(store: DataStore<Preferences>, settingsStore: DataStore<Preferences> = Memory()): ApRepository {
        val settings = AppSettingsRepository(settingsStore); settings.save(settingsValue)
        return ApRepository(store, settings)
    }
    @Test fun oldPayloadImportsWithoutInventedDates() {
        val s = ApCodec.importLegacy(ApState(), IncidentsCodec.decode(payload))
        val r = s.requests.single(); assertEquals("old-ap", r.id); assertTrue(r.legacy); assertNull(r.requestedAt)
        assertEquals(2, r.days.size); r.days.forEach { assertEquals(ApStatus.CONCEDIDO, it.status); assertNull(it.resolvedAt); assertNull(it.reason); assertTrue(it.history.isEmpty()) }
        assertEquals(6, s.balances(date).single().available)
    }
    @Test fun oldPermissionAndVacationPreservedExactly() {
        val all = IncidentsCodec.decode(payload)
        assertEquals(DateIncident("old-permission", IncidentType.PERMISSION, listOf(LocalDate.of(2026,12,7), LocalDate.of(2027,1,5))), all[1])
        assertEquals(VacationIncident("old-vacation", LocalDate.of(2026,12,28), LocalDate.of(2027,1,2)), all[2])
        assertEquals(payload, IncidentsCodec.encode(all))
    }
    @Test fun importIsIdempotentAndDoesNotResurrectCancelledLegacy() {
        val legacy = IncidentsCodec.decode(payload)
        val s = ApCodec.importLegacy(ApState(), legacy)
        val calculator = es.robertodorado.cuadrante.calculation.ShiftCalculator(date, listOf(ShiftType.MORNING))
        val updated = ApPolicy.apply(s, emptyList(), calculator, ApChange.Resolve(s.days.first().id, ApStatus.CANCELADO), now)
        val twice = ApCodec.importLegacy(ApCodec.decode(ApCodec.encode(updated)), legacy)
        assertEquals(updated, twice); assertEquals(ApStatus.CANCELADO, twice.days.first().status)
        assertEquals(ApStatus.CONCEDIDO, twice.days.first().history.first().status)
    }
    @Test fun newCodecRoundTripIncludesTextSeparatorsUnicodeAndHistory() {
        val s = ApCodec.importLegacy(ApState(), IncidentsCodec.decode(payload))
        val day = s.days.first().copy(notes = "ñ|\n👍", reason = "motivo").recorded(now, "edición")
        val value = s.copy(requests = listOf(s.requests.first().copy(days = listOf(day))))
        assertEquals(value, ApCodec.decode(ApCodec.encode(value)))
    }
    @Test fun unknownSidecarDoesNotFallBackToEmpty() { assertThrows(IllegalArgumentException::class.java) { ApCodec.decode("AAAAAg==") } }
    @Test fun legacyExtendedRecordStillReadsValidPrefix() { assertEquals(IncidentsCodec.decode(payload), IncidentsCodec.decode(payload.lineSequence().joinToString("\n") { "$it|future-field" })) }
    @Test fun migrationAndNewChangesKeepOriginalBytes() = runBlocking {
        val store = Memory(); store.edit { it[ApRepository.legacyKey] = payload + "\nX|future|untouched" }
        val repo = repository(store)
        assertEquals(3, repo.incidents.first().size) // one grouped AP, one permission, one vacation
        val proposal = repo.preview(ApChange.Resolve(repo.state.first().days.first().id, ApStatus.CANCELADO), now)
        repo.confirm(proposal, Confirmation.CONFIRM)
        assertEquals(payload + "\nX|future|untouched", store.data.first()[ApRepository.legacyKey])
        assertEquals(2, repo.state.first().days.size)
    }
    @Test fun previewAndCancelDoNotWrite() = runBlocking {
        val store = Memory(); val repo = repository(store)
        val p = repo.preview(ApChange.ConfigurePool(ApPool(2026)), now)
        assertEquals(0, store.writes)
        try { repo.confirm(p, Confirmation.CANCEL); fail("Must not commit") } catch (_: IllegalArgumentException) { }
        assertEquals(0, store.writes); assertTrue(repo.state.first().pools.isEmpty())
    }
    private suspend fun configure(repo: ApRepository) { repo.confirm(repo.preview(ApChange.ConfigurePool(ApPool(2026)), now), Confirmation.CONFIRM) }
    @Test fun explicitConfirmationCommitsExactlyOnce() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo)
        val p = repo.preview(create(), now); assertEquals(1, store.writes)
        repo.confirm(p, Confirmation.CONFIRM); assertEquals(2, store.writes)
        try { repo.confirm(p, Confirmation.CONFIRM); fail("Stale proposal") } catch (_: IllegalArgumentException) { }
        assertEquals(2, store.writes)
    }
    @Test fun invalidMultiDateEditWritesNothing() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo)
        repo.confirm(repo.preview(create(), now), Confirmation.CONFIRM)
        val before = store.data.first(); val writes = store.writes
        val change = ApChange.Edit("r", listOf(ApSelection("r-day", date.plusDays(1),2026), ApSelection("new",date.plusDays(2),2027)))
        try { repo.preview(change, now); fail("Invalid pool") } catch (_: ApValidationException) { }
        assertEquals(writes, store.writes); assertEquals(before, store.data.first())
    }
    @Test fun validMultiDateEditWritesOnce() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo); repo.confirm(repo.preview(create(), now), Confirmation.CONFIRM)
        val writes = store.writes
        val change = ApChange.Edit("r", listOf(ApSelection("r-day",date.plusDays(1),2026),ApSelection("new",date.plusDays(2),2026)))
        repo.confirm(repo.preview(change, now),Confirmation.CONFIRM)
        assertEquals(writes + 1, store.writes); assertEquals(2, repo.state.first().days.size)
    }
    @Test fun failedPoolChangeDoesNotReleaseOldReservation() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo); repo.confirm(repo.preview(create(),now), Confirmation.CONFIRM)
        val before = store.data.first(); val writes = store.writes
        try { repo.preview(ApChange.Reassign("r-day",2027),now); fail("Invalid pool") } catch (_: ApValidationException) { }
        assertEquals(before,store.data.first()); assertEquals(writes,store.writes)
    }
    @Test fun validPoolChangeIsOneAtomicWrite() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo)
        repo.confirm(repo.preview(ApChange.ConfigurePool(ApPool(2025, extensionUntil = LocalDate.of(2027,3,1))),now),Confirmation.CONFIRM)
        repo.confirm(repo.preview(create(),now),Confirmation.CONFIRM); val writes = store.writes
        repo.confirm(repo.preview(ApChange.Reassign("r-day",2025),now),Confirmation.CONFIRM)
        assertEquals(writes+1,store.writes); assertEquals(2025,repo.state.first().days.single().poolYear)
    }
    @Test fun concurrentProposalsCannotOverbook() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo)
        val first = repo.preview(create("a"),now); val second = repo.preview(create("b",1),now)
        repo.confirm(first,Confirmation.CONFIRM)
        try { repo.confirm(second,Confirmation.CONFIRM); fail("Stale") } catch (_: IllegalArgumentException) { }
        assertEquals(1,repo.state.first().days.size)
    }
