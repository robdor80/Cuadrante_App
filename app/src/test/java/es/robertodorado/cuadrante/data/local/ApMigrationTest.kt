    @Test fun legacyWriterPreservesUnknownRecordsAndBlocksApBypass() = runBlocking {
        val store = Memory(); val old = IncidentsRepository(store)
        store.edit { it[ApRepository.legacyKey] = payload + "\nX|unknown|data" }
        old.add(DateIncident("new",IncidentType.PERMISSION,listOf(date.plusDays(10))))
        assertTrue(store.data.first()[ApRepository.legacyKey]!!.contains("X|unknown|data"))
        val before = store.data.first()
        try { old.add(DateIncident("bypass",IncidentType.AP,listOf(date))); fail("Bypass") } catch (_: IllegalArgumentException) { }
        try { old.delete("old-ap"); fail("History must remain") } catch (_: IllegalArgumentException) { }
        assertEquals(before,store.data.first())
    }
    @Test fun permissionAndVacationCannotOverwriteActiveAp() = runBlocking {
        val store = Memory(); val repo = repository(store); configure(repo); repo.confirm(repo.preview(create(),now),Confirmation.CONFIRM)
        val old = IncidentsRepository(store); val before = store.data.first()
        for (incident in listOf(DateIncident("p",IncidentType.PERMISSION,listOf(date)),VacationIncident("v",date,date))) {
            try { old.add(incident); fail("Overlap") } catch (_: IllegalArgumentException) { }
        }
        assertEquals(before,store.data.first())
    }
    @Test fun unknownSidecarBlocksAllWritersWithoutLosingBytes() = runBlocking {
