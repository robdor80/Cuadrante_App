        val before = store.data.first()
        try { repo.preview(ApChange.ConfigurePool(ApPool(2026)),now); fail("Unknown version") } catch (_: IllegalArgumentException) { }
        try { IncidentsRepository(store).add(DateIncident("p",IncidentType.PERMISSION,listOf(date.plusDays(10)))); fail("Unknown version") } catch (_: IllegalArgumentException) { }
        assertEquals(before,store.data.first())
    }
    @Test fun realDataStoreUpgradeAndReopenPreservesAllData() = runBlocking {
        val scope = CoroutineScope(Dispatchers.IO + SupervisorJob())
        val settingsScope = CoroutineScope(Dispatchers.IO + SupervisorJob())
        val path = File(folder.root,"incidents.preferences_pb")
        val settingsPath = File(folder.root,"app_settings.preferences_pb")
        val settingsStore = PreferenceDataStoreFactory.create(scope = settingsScope) { settingsPath }
        val store = PreferenceDataStoreFactory.create(scope = scope) { path }
        val repo = repository(store, settingsStore)
        store.edit { it[ApRepository.legacyKey] = payload }
        val legacy = repo.state.first(); assertEquals(2,legacy.days.size)
        repo.confirm(repo.preview(ApChange.Resolve(legacy.days.first().id,ApStatus.CANCELADO),now),Confirmation.CONFIRM)
        val expected = repo.state.first()
        scope.coroutineContext[Job]!!.cancelAndJoin(); settingsScope.coroutineContext[Job]!!.cancelAndJoin()
        val reopenScope = CoroutineScope(Dispatchers.IO + SupervisorJob())
        val reopenSettingsScope = CoroutineScope(Dispatchers.IO + SupervisorJob())
        try {
            val reopened = PreferenceDataStoreFactory.create(scope = reopenScope) { path }
            val reopenedSettings = PreferenceDataStoreFactory.create(scope = reopenSettingsScope) { settingsPath }
            val reloaded = ApRepository(reopened,AppSettingsRepository(reopenedSettings))
            assertEquals(payload,reopened.data.first()[ApRepository.legacyKey]); assertEquals(expected,reloaded.state.first())
            assertEquals(IncidentsCodec.decode(payload).filter { it.type != IncidentType.AP },reloaded.incidents.first().filter { it.type != IncidentType.AP })
            assertEquals(settingsValue,AppSettingsRepository(reopenedSettings).settings.first())
        } finally { reopenScope.cancel(); reopenSettingsScope.cancel() }
    }
    @Test fun markersUseShapeAndStateAndKeepDeniedVisible() {
        val days = ApStatus.entries.mapIndexed { i,status -> ApDay("$i",date.plusDays(i.toLong()),status,2026) }
        val request = ApRequest("r",now,days)
        val markers = incidentMarkersByDate(listOf(request),YearMonth.from(date))
        assertEquals(3,markers.size); assertEquals("●",markers[date]!!.single().symbol)
        assertEquals(ApStatus.DENEGADO,markers[date.plusDays(2)]!!.single().status)
        assertFalse(markers.containsKey(date.plusDays(3)))
        assertEquals(listOf(date,date.plusDays(1),date.plusDays(2)),incidentsForMonth(listOf(request),YearMonth.from(date)).single().datesInMonth)
    }
