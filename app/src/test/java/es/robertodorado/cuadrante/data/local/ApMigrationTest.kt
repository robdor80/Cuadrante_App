    @Test fun markerColorsHaveContrastInBothThemes() {
        for (dark in listOf(false,true)) {
            val background = if (dark) androidx.compose.ui.graphics.Color(0xFF101820) else androidx.compose.ui.graphics.Color.White
            for (status in listOf(ApStatus.SOLICITADO,ApStatus.CONCEDIDO,ApStatus.DENEGADO)) {
                val color = status.statusColor(dark)
                val a = color.luminance(); val b = background.luminance()
                assertTrue((maxOf(a,b)+0.05f)/(minOf(a,b)+0.05f) >= 4.5f)
            }
        }
    }

